-- ============================================================================
-- V15：账户级押金（2026-10-10 定稿 定-1 / S-03 新口径）
--
-- 原来押金是"每单收一次、单结束退一次"，所以它挂在订单与 biz_deposit 上。
-- 用户定的口径是"账户里押着 50 元，交一次反复用，不用了再退"——那它就不是订单的属性，
-- 而是账户的一栏，与 points（可花）、frozen_points（答应要还的）并列第三栏。
--
-- 三栏分开的理由和原来两栏一样：合起来就答不出"还能花多少 / 答应还多少 / 押着多少"。
-- 记账上配四个流水类型（划出/划入、退回出/退回入），**一笔只动一栏**，
-- 这样"某栏 == 该栏类型流水求和"这条对账判据仍然成立（见 PointTxnType 的类注释）。
--
-- 历史每单押金不搬运：旧单的押金仍按它自己订单上的金额与快照退还（代码里 deposit>0 才走那条路），
-- 新单押金为 0。所以不需要数据迁移，也**不能**在迁移里凭空给用户加一笔钱——那是造出来的余额。
-- ============================================================================

ALTER TABLE biz_point_account
    ADD COLUMN deposit_points BIGINT NOT NULL DEFAULT 0
        COMMENT '账户级押金（划出后不可花、不参与消费），用户不再使用时退回 points';

-- 说明：没给这栏加 CHECK(>=0)。要加得先 DROP 原有 CHECK 再重建整条约束，
-- 而并发正确性靠的是服务层的条件 UPDATE（changeDeposit 的 WHERE），CHECK 只是挡手误的第二道。
-- 这条欠账显式记在 docs/架构约定.md，不是漏掉。
