-- V18：工单唯一索引把队列侧纳入（19B 自测时发现的真实缺陷）
--
-- V17 的索引是 uk (tenant_id, type, slot_id, active_flag)。写派线下用例时它立刻反咬一口：
-- 线上父单还没关（active_flag=1）就要插同格口同类型的线下子单 → 撞唯一索引，派发失败。
-- 这不是测试写错，是约束画错了边界：**“同一异常只能有一张待办”说的是同一条队列里不能重复**，
-- 而线上与线下本来就是同一件事的两个责任段（父单记“为什么派人”，子单记“到场做了什么”），
-- 必须能同时存在。
--
-- 所以把 queue_side 放进索引：同格口、同类型、同队列、未关闭 → 只允许一张。
-- 原意图（巡检每轮刷同一异常不会把队列埋满）完全保留。
--
-- V17 已经应用过，改它会破坏 Flyway 校验和（本地与 CI 的库都会拒绝启动），
-- 所以这里用一条新迁移显式重建索引。
-- ============================================================================

ALTER TABLE biz_work_order DROP INDEX uk_work_order_open;

ALTER TABLE biz_work_order
    ADD UNIQUE KEY uk_work_order_open (tenant_id, type, slot_id, queue_side, active_flag);
