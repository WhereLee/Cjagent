-- V16：预收取代押金与预估冻结（2026-10-11 用户定稿，第 19 刀 19A）
--
-- 资金模型换成一句话：**下单先收 4 小时的钱，结束时按实际时长算，多退少补。**
-- 所以订单上要记住的不是“冻了多少”而是“预收了多少”——这两个数的义务完全不同：
--   冻结是“答应要还的”，结算时要么核销要么解冻；
--   预收是“已经收进来的收入”，结算时要么退差额（一笔退还流水）要么补扣（欠费就记未支付）。
-- 把它记成 frozen_points 会让对账把一笔真实收入当成负债核销掉，所以另开一列。
--
-- 没删的三样东西，都不是遗漏：
--   1) `frozen_points` / `deposit_points` 列保留：在途单与历史单的流水还指着它们，
--      删列会让“某栏 == 该栏流水求和”这条自证判据读不到历史；
--   2) `biz_deposit` 表保留：同理，历史每单押金的退还记录是可审计事实；
--   3) 押金四个流水类型保留：只停“产生”，不停“解读”，否则历史流水解析不出类型会炸。
--      业务代码里不再产生新的押金/冻结流水（19A 同时删掉了退押金入口与未退清单）。
-- ============================================================================

ALTER TABLE biz_storage_order
    ADD COLUMN prepay_points BIGINT NOT NULL DEFAULT 0
        COMMENT '下单预收点数（= 该格口 4 小时费用）；结算按实际时长多退少补，本列不是负债';
