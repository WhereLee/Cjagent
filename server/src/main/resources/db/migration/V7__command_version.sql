-- ============================================================================
-- V7: 给设备指令补乐观锁列（第 11 刀）
--
-- 为什么必须加，而不是把实体上的 @Version 删掉省事：
-- 同一条指令会被两条路径并发写——① 设备回执到达；② 超时回扫（第 13 刀）把它判 TIMEOUT。
-- 没有版本列时是"后提交者覆盖"，最坏的顺序是：回扫先读到 SENT，回执线程把它改成 SUCCEEDED 并提交，
-- 回扫随后按自己手里的旧对象写回 TIMEOUT —— 结果系统认为门没开，而件可能已经在柜里。
-- 这正是本项目最不能接受的一类不一致，所以用乐观锁把丢更新挡住（写冲突时重试或放弃由业务判断）。
--
-- 不加 CHECK 约束等花活：状态合法性由 CommandState 的迁移表在代码层保证，
-- SQL 层再写一套枚举白名单只会变成两处要同步改的真相源。
-- ============================================================================

ALTER TABLE biz_device_command
    ADD COLUMN version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本：防回执与超时回扫互相覆盖' AFTER last_error;
