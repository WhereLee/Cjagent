-- ============================================================================
-- V14：取件码错次锁定（2026-10-10 用户定稿 定-6）
--
-- 为什么现在才加这两列：取件码（voucherCode）从第 8 刀就生成了，但**从来没有被校验过**
-- ——取件走的是登录态，那个码只是个装饰。用户定了"柜机上输码取件"是手机没电时的
-- 第二条路径之后，码才第一次变成真凭据；是凭据就要能防猜，所以要记错次并锁定。
--
-- 阈值 5 次由用户给出，写在服务层常量里，不进库（一列一个参数会漂；配置与代码两份
-- 也更难对齐）。锁定的出路不在这里：客服核验 → 后台强制开柜（既有路径，带审计）。
-- ============================================================================

ALTER TABLE biz_storage_order
    ADD COLUMN voucher_wrong_count INT         NOT NULL DEFAULT 0
        COMMENT '取件码连续输错次数（校验通过即清零）',
    ADD COLUMN voucher_locked_at   DATETIME(3) NULL
        COMMENT '输错达阈值而锁定该单开柜能力的时刻；非空即锁定，只能人工解除';
